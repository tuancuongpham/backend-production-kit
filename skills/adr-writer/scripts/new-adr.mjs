#!/usr/bin/env node
// Create the next numbered ADR from the template and refresh the index.
// Usage: node new-adr.mjs "Use RLS for tenant isolation" [--dir docs/adr] [--status Proposed] [--supersedes 3]
import { mkdir, readdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));

function parseArgs(argv) {
  const out = { title: '', dir: 'docs/adr', status: 'Proposed', supersedes: null };
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a === '--dir') out.dir = argv[++i];
    else if (a === '--status') out.status = argv[++i];
    else if (a === '--supersedes') out.supersedes = Number(argv[++i]);
    else out.title = out.title ? `${out.title} ${a}` : a;
  }
  if (!out.title) {
    console.error('usage: new-adr.mjs "<title>" [--dir docs/adr] [--status Proposed] [--supersedes N]');
    process.exit(2);
  }
  return out;
}

export function slugify(title) {
  return title
    .replace(/đ/g, 'd')
    .replace(/Đ/g, 'D')
    .normalize('NFD')
    .replace(/[̀-ͯ]/g, '') // strip diacritics (Vietnamese and others)
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
    .slice(0, 60)
    .replace(/-+$/, '');
}

const pad = (n) => String(n).padStart(4, '0');
const ADR_FILE = /^(\d{4})-.+\.md$/;

async function listAdrs(dir) {
  const files = (await readdir(dir).catch(() => [])).filter((f) => ADR_FILE.test(f)).sort();
  return Promise.all(
    files.map(async (file) => {
      const text = await readFile(path.join(dir, file), 'utf8');
      return {
        file,
        number: Number(file.slice(0, 4)),
        title: (text.match(/^# (.+)$/m)?.[1] ?? file).trim(),
        status: (text.match(/^- \*\*Status:\*\* (.+)$/m)?.[1] ?? 'Unknown').trim(),
      };
    }),
  );
}

async function writeIndex(dir) {
  const adrs = await listAdrs(dir);
  const rows = adrs.map((a) => `| [${pad(a.number)}](${a.file}) | ${a.title.replace(/^ADR-\d{4}: /, '')} | ${a.status} |`);
  const body = `# Architecture Decision Records\n\nGenerated by \`new-adr.mjs\`. Do not edit the table by hand.\n\n| # | Decision | Status |\n|---|---|---|\n${rows.join('\n')}\n`;
  await writeFile(path.join(dir, 'README.md'), body);
}

async function main() {
  const args = parseArgs(process.argv.slice(2));
  const dir = path.resolve(args.dir);
  await mkdir(dir, { recursive: true });
  const existing = await listAdrs(dir);
  const number = Math.max(0, ...existing.map((a) => a.number)) + 1;
  const file = `${pad(number)}-${slugify(args.title) || 'decision'}.md`;
  const template = await readFile(path.join(here, '..', 'assets', 'adr-template.md'), 'utf8');
  const date = new Date().toISOString().slice(0, 10);
  let content = template
    .replaceAll('{{NUMBER}}', pad(number))
    .replaceAll('{{TITLE}}', args.title)
    .replaceAll('{{DATE}}', date)
    .replaceAll('{{STATUS}}', args.status);

  if (args.supersedes) {
    const old = existing.find((a) => a.number === args.supersedes);
    if (!old) {
      console.error(`ADR ${args.supersedes} not found`);
      process.exit(1);
    }
    const oldPath = path.join(dir, old.file);
    const oldText = await readFile(oldPath, 'utf8');
    await writeFile(oldPath, oldText.replace(/^- \*\*Status:\*\* .+$/m, `- **Status:** Superseded by [ADR-${pad(number)}](${file})`));
    content = content.replace(/^- \*\*Related:\*\* .+$/m, `- **Related:** Supersedes [ADR-${pad(old.number)}](${old.file})`);
  }

  await writeFile(path.join(dir, file), content);
  await writeIndex(dir);
  console.log(path.join(args.dir, file));
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await main();
}
